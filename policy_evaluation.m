function [coeff] = policy_evaluation(config, cur_state, cur_ctl, nxt_state,...
    coeff_ini, J2L_mat, theta_max, trust_region_r, Hamilton_diff,...
    J_hamilton_fun, unit_ball_sample, non_zero_count)
%
coeff = coeff_ini;
opts = optimoptions("fmincon", 'Algorithm', "sqp", 'MaxIterations', 500,'MaxFunctionEvaluations',500);
%% 下面利用对偶性原理松弛求解值函数 V_T, V_R

coeff(:, 1) = fmincon(@(coeff) tgt_fun_po_ev(config, cur_state, coeff), ...
    coeff_ini(:, 1), [],[],[],[],[],[], @(coeff) quardic_cst(config, ...
    cur_state, cur_ctl, nxt_state, J2L_mat, theta_max, coeff_ini(:, 1), ...
    coeff, trust_region_r, Hamilton_diff, J_hamilton_fun, "V_T", ...
    unit_ball_sample, non_zero_count), opts);
coeff(:, 2) = fmincon(@(coeff) tgt_fun_po_ev(config, cur_state, coeff), ...
    coeff_ini(:, 2), [],[],[],[],[],[], @(coeff) quardic_cst(config, ...
    cur_state, cur_ctl, nxt_state, J2L_mat, theta_max, coeff_ini(:, 2), ...
    coeff, trust_region_r, Hamilton_diff, J_hamilton_fun, "V_R", ...
    unit_ball_sample, non_zero_count), opts);

end